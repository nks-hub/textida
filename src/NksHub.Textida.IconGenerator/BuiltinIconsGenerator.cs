using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using NksHub.Textida.Workbench.Icons;

namespace System.Runtime.CompilerServices
{
    /// <summary>Lets the records of the linked sources compile for netstandard2.0.</summary>
    internal static class IsExternalInit
    {
    }
}

namespace NksHub.Textida.IconGenerator
{
    /// <summary>
    /// Turns the SVG files of the built-in icons (the <c>Icons/svg</c> folder of the workbench project, passed as additional files) into C# when the program is built: one entry per file in
    /// <c>BuiltinIcons</c>, holding the path data and how each path is drawn. The program therefore never reads an SVG file at run time for its own icons (the NativeAOT build has no use for a reader), and a file
    /// that the reader of plugin icons refuses stops the build.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class BuiltinIconsGenerator : IIncrementalGenerator
    {
        private static readonly DiagnosticDescriptor Refused = new(
            "ICON001", "Icon file refused", "{0}: {1}", "Icons", DiagnosticSeverity.Error, isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var files = context.AdditionalTextsProvider
                .Where(f => f.Path.EndsWith(".svg", StringComparison.OrdinalIgnoreCase))
                .Select((f, ct) => new SvgFile(f.Path, f.GetText(ct)?.ToString() ?? ""))
                .Collect();
            context.RegisterSourceOutput(files, Emit);
        }

        private static void Emit(SourceProductionContext context, System.Collections.Immutable.ImmutableArray<SvgFile> files)
        {
            var icons = new SortedDictionary<string, IconShape>(StringComparer.Ordinal);
            foreach (var file in files)
            {
                string name = Path.GetFileNameWithoutExtension(file.Path);
                if (!IsName(name))
                {
                    context.ReportDiagnostic(Diagnostic.Create(Refused, Location.None, file.Path, "the file name must be lower case letters, digits and '-', starting with a letter"));
                    continue;
                }

                if (icons.ContainsKey(name))
                {
                    context.ReportDiagnostic(Diagnostic.Create(Refused, Location.None, file.Path, "another file has the same name"));
                    continue;
                }

                if (!SvgIcon.TryParse(file.Text, out var shape, out var error) || shape is null)
                {
                    context.ReportDiagnostic(Diagnostic.Create(Refused, Location.None, file.Path, error));
                    continue;
                }

                icons.Add(name, shape);
            }

            var code = new StringBuilder();
            code.AppendLine("// <auto-generated>From the SVG files in Icons/svg; do not edit.</auto-generated>");
            code.AppendLine("#nullable enable");
            code.AppendLine("namespace NksHub.Textida.Workbench.Icons;");
            code.AppendLine();
            code.AppendLine("public static partial class BuiltinIcons");
            code.AppendLine("{");
            code.AppendLine("    private static Dictionary<string, IconShape> Build() => new(StringComparer.Ordinal)");
            code.AppendLine("    {");
            foreach (var pair in icons)
            {
                code.Append("        [").Append(Literal(pair.Key)).Append("] = new IconShape(").Append(pair.Value.Size.ToString(CultureInfo.InvariantCulture)).AppendLine(", [");
                foreach (var path in pair.Value.Paths)
                {
                    code.Append("            new IconPath(").Append(Literal(path.Data)).Append(", IconPaint.").Append(path.Paint.ToString()).AppendLine("),");
                }

                code.AppendLine("        ]),");
            }

            code.AppendLine("    };");
            code.AppendLine("}");
            context.AddSource("BuiltinIcons.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
        }

        private static bool IsName(string name) =>
            name.Length is > 0 and <= 48 && name[0] is >= 'a' and <= 'z' && name.All(c => c is >= 'a' and <= 'z' or >= '0' and <= '9' or '-');

        private static string Literal(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        private sealed class SvgFile
        {
            public SvgFile(string path, string text)
            {
                Path = path;
                Text = text;
            }

            public string Path { get; }

            public string Text { get; }
        }
    }
}
